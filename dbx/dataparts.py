def getenv(key: str, default: str|None = None) -> str:
    """Return the value of environment variable *key*.

    Intended to be referenced in speclines so that handles contain the
    symbolic ``$dbx.getenv('KEY')`` rather than the resolved path.
    """
    if isinstance(key, str):
        key = key.strip("'\"")
    if isinstance(default, str):
        default = default.strip("'\"")
    if default is not None:
        return os.environ.get(key, default)
    try:
        return os.environ[key]
    except KeyError:
        raise EnvironmentError(
            f"Required environment variable '{key}' is not set. "
            f"Please set it before running this pipeline, e.g.: "
            f"export {key}=<value>"
        ) from None


def env(key: str, default: str|None = None) -> str:
    """Return a specline that lazily resolves an environment variable.

    Usage::

        from dbx import env
        MyBlock(root=env('FACTION_DATAROOT'), spec=dict(path=env('MY_PATH')))

    The returned string is a specline (``$``-prefixed) that the existing
    dbx eval/expand machinery keeps symbolic in handles and evaluates to
    the real value in var / __init__.
    """
    if isinstance(key, str) and key.startswith('$'):
        # Already a specline — idempotent.
        return key
    if default is None:
        return f"$dbx.getenv('{key}')"
    return f"$dbx.getenv('{key}', '{default}')"


class Logger:
    """Lightweight, printf-style logger with level gating.

    Levels (from most to least severe): ``ERROR``, ``WARNING``, ``INFO``,
    ``VERBOSE``, ``SELECTED``, ``DEBUG``, ``DETAILED``.

    Each level can be enabled via constructor keyword, environment
    variable (``DBX_LOG_<LEVEL>``), or built-in default.

    Parameters
    ----------
    name : str, optional
        Prefix printed before every message.
    warning, info, verbose, debug, selected, detailed : bool, optional
        Override the default enable/disable for each level.
    selection : str or list[str], optional
        Fully-qualified function names that ``selected()`` should emit
        for.  Comma-separated string or list.  Falls back to
        ``DBX_LOG_SELECTION``.
    datetime : bool
        Include ISO-8601 timestamp in output (default ``True``).
    stack_depth : int
        Caller-frame offset for function-name tagging (default ``2``).
    """

    def __init__(
        self,
        name: Optional[str] = None,
        *,
        warning: bool = None,
        info: bool = None,
        verbose: bool = None,
        debug: bool = None,
        selected: bool = None,
        detailed: bool = None,
        selection: Union[str, Sequence[str]] = None,
        datetime: bool = True,
        stack_depth: int = 2,
    ):
        self.stack_depth = stack_depth
        self.name = name
        self.datetime = datetime
        self.allowed = ["ERROR"]
        
        _defaults_ = {
            'warning': True,
            'info': True,
            'verbose': False,
            'selected': True,
            'debug': False,
            'detailed': False,
            'selection': None,
        }
        def set_arg(name, locals):
            """Prioritize kwarg value, fall back to env var, then to default."""
            # Get kwarg value from local scope
            kwarg_value = locals.get(name)
            if kwarg_value is not None:
                result = kwarg_value
            else:
                # Generate env key: 'warning' -> 'DBX_LOG_WARNING'
                env_key = f'DBX_LOG_{name.upper()}'
                env_val = os.environ.get(env_key)
                if env_val is not None:
                    try:
                        result = __eval__(env_val)
                    except (NameError, SyntaxError):
                        result = env_val
                else:
                    result = _defaults_[name]
            setattr(self, f'_{name}_', result)
            if result and name != 'selection':
                self.allowed.append(name.upper())
        
        for argname in _defaults_.keys():
            set_arg(argname, locals())
        
        if self._selection_ is None:
            self._selection_ = []
        elif isinstance(self._selection_, str):
            self._selection_ = [s.strip() for s in self._selection_.split(',')]
        if len(self._selection_) == 0:
            self._selection_ = os.environ.get('DBX_LOG_SELECTION')
            if self._selection_ is not None:
                self._selection_ = [s.strip() for s in self._selection_.split(',')]
            
    def get(self, key):
        return getattr(self, f"_{key}_")
    
    def ist(self, key):
        return getattr(self, f"_{key}_")


    def _print(self, prefix, msg):
        """
        #TODO: figure out why the next line causes things to hang sometimes
        stack = inspect.stack() 
        if self.stack_depth is None or self.stack_depth >= len(stack):
            func = None
        else:
            frame = stack[self.stack_depth]
            func = frame.function
        """
        func = None
        
        if self.name is None:
            if func is None:
                tag = ""
            else:
                tag = f"{func}: "
        else:
            if func is None:
                tag = f"{self.name}: "
            else:
                tag = f"{self.name}: {func}: "
        if prefix in self.allowed:
            dt = f"{datetime.datetime.now().isoformat()}: " if self.datetime else ""
            print(f"{prefix}: {dt}{tag}{msg}")

    def _fmt(self, msg, args):
        """Format message stdlib-style: msg % args when args are provided."""
        if args:
            try:
                return msg % args
            except (TypeError, ValueError):
                return f"{msg} {args}"
        return msg

    def error(self, msg, *args, **kwargs):
        self._print("ERROR", self._fmt(msg, args))

    def warning(self, msg, *args, **kwargs):
        self._print("WARNING", self._fmt(msg, args))

    def warn(self, msg, *args, **kwargs):
        self._print("WARNING", self._fmt(msg, args))

    def info(self, msg, *args, **kwargs):
        self._print("INFO", self._fmt(msg, args))

    def debug(self, msg, *args, **kwargs):
        self._print("DEBUG", self._fmt(msg, args))

    def verbose(self, msg, *args, **kwargs):
        self._print("VERBOSE", self._fmt(msg, args))

    def selected(self, msg, *args, **kwargs):
        if not self._selection_:
            return
        frame = sys._getframe(self.stack_depth - 1)
        module = frame.f_globals.get('__name__')
        qualname = frame.f_code.co_qualname  # e.g. "MyClass.tag" (Python 3.11+)
        function = frame.f_code.co_name      # e.g. "tag"
        fqn_full  = f"{module}.{qualname}"   # "pkg.mod.MyClass.tag"
        fqn_short = f"{module}.{function}"   # "pkg.mod.tag"
        if fqn_full not in self._selection_ and fqn_short not in self._selection_:
            return
        self._print("SELECTED", self._fmt(msg, args))

    def detailed(self, msg, *args, **kwargs):
        self._print("DETAILED", self._fmt(msg, args))

    def silent(self, msg, *args, **kwargs):
        pass


class OutputTee:
    """Tee OS-level stdout/stderr (FDs 1 & 2) to a log file.

    This MIRRORS rather than swallows: every byte still reaches the terminal.
    Both descriptors are redirected into pipes, and a pump thread writes each
    chunk twice -- once back to the saved original fd (so you keep seeing it)
    and once to *log_file*.

    Capturing at the file-descriptor level, rather than by replacing
    ``sys.stdout``/``sys.stderr``, is what makes it complete.  A Python-level
    tee only sees writes that go through the Python stream object, and so
    misses:

      * C extensions writing straight to fd 1/2 (BLAS, CUDA, native loggers);
      * subprocesses, which inherit the file descriptors, not ``sys.stdout``;
      * any code holding a reference to the real stream captured before the
        swap.

    ``dup2`` replaces the descriptors themselves, so all three land in the log.

    Ordering between the two destinations is best-effort: the pump is
    asynchronous and Python block-buffers a non-tty stdout, so interleaving of
    Python-level and fd-level writes can differ from a direct run.
    """
    def __init__(self, log_file):
        self.log_file = log_file
        
        self.saved_stdout_fd = os.dup(1)
        self.saved_stderr_fd = os.dup(2)
        
        self.stdout_pipe_r, self.stdout_pipe_w = os.pipe()
        self.stderr_pipe_r, self.stderr_pipe_w = os.pipe()

        os.dup2(self.stdout_pipe_w, 1)
        os.dup2(self.stderr_pipe_w, 2)
        
        self.stop_event = threading.Event()
        
        def pump(pipe_r, original_fd, log_f):
            while not self.stop_event.is_set():
                try:
                    data = os.read(pipe_r, 4096)
                    if not data:
                        break
                    os.write(original_fd, data)
                    # We write binary to the log file since os.read gives bytes.
                    # If log_f is opened in text mode, we must decode.
                    if hasattr(log_f, 'buffer'):
                        log_f.buffer.write(data)
                        log_f.buffer.flush()
                    else:
                        log_f.write(data.decode('utf-8', errors='replace'))
                        log_f.flush()
                except OSError:
                    break
                    
        self.t_out = threading.Thread(target=pump, args=(self.stdout_pipe_r, self.saved_stdout_fd, self.log_file))
        self.t_err = threading.Thread(target=pump, args=(self.stderr_pipe_r, self.saved_stderr_fd, self.log_file))
        
        self.t_out.daemon = True
        self.t_err.daemon = True
        self.t_out.start()
        self.t_err.start()

    def close(self):
        sys.stdout.flush()
        sys.stderr.flush()
        
        os.dup2(self.saved_stdout_fd, 1)
        os.dup2(self.saved_stderr_fd, 2)
        
        os.close(self.stdout_pipe_w)
        os.close(self.stderr_pipe_w)
        
        self.t_out.join()
        self.t_err.join()
        
        os.close(self.stdout_pipe_r)
        os.close(self.stderr_pipe_r)
        
        os.close(self.saved_stdout_fd)
        os.close(self.saved_stderr_fd)


