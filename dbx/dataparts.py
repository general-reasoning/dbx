def ls_path(fs, p, path_is_dir, *, detail=False):
    """List the contents at *p* on *fs*.

    When *p* genuinely points to a file (``path_is_dir`` is False and *fs*
    reports a file) its parent directory is listed instead.  Directory paths get a
    trailing "/" so Azure adlfs returns the directory's *contents* rather
    than the virtual-directory marker.  Returns ``[]`` when *p* is absent.
    """
    if p is None or not fs.exists(p):
        return []
    # Only fall back to the parent directory when the path genuinely points
    # to a file; fs.isfile() may be a false positive on Azure virtual dirs.
    if not path_is_dir and fs.isfile(p):
        p = os.path.dirname(p)
    if path_is_dir and not p.endswith('/'):
        p = p + '/'
    results = fs.ls(p, detail=detail)
    if detail:
        for entry in results:
            entry['name'] = fs_full_path(fs, entry['name'])
        return results
    return [fs_full_path(fs, x) for x in results]


def list_path(fs, p, path_is_dir):
    """Detailed, recursive listing of every file under *p* on *fs*.

    Directory entries are excluded; a single-file path returns just that
    file.  Each returned dict has its ``name`` normalized to a
    fully-qualified path.  Returns ``[]`` when *p* is absent.
    """
    if p is None or not fs.exists(p):
        return []
    if not path_is_dir and fs.isfile(p):
        info = dict(fs.info(p))
        info['name'] = fs_full_path(fs, info.get('name', p))
        return [info]
    if path_is_dir and not p.endswith('/'):
        p = p + '/'
    detail = fs.find(p, withdirs=False, detail=True)
    results = []
    for name, info in detail.items():
        info = dict(info)
        info['name'] = fs_full_path(fs, info.get('name', name))
        results.append(info)
    return results


def size(entries):
    """Sum the ``size`` of every file detail dict in *entries*."""
    return sum((entry.get('size') or 0) for entry in entries)

def quotefn(fn, *args, tag="$", **kwargs):
    log = Logger()
    if callable(fn):
        fn = f"{fn.__module__}.{fn.__qualname__}"
    def quote_arg(arg):
        q = quote(arg)
        if isinstance(q, str) and (q.startswith("$") or q.startswith("@") or q.startswith("#")):
            return json.dumps(q)
        return str(q)
    argstrs = [quote_arg(arg) for arg in args]
    kwargstrs = [f"{k}={quote_arg(v)}" for k, v in kwargs.items()]
    argkwargstr = ','.join(argstrs+kwargstrs)
    _quote = f"{tag}{fn}({argkwargstr})"
    log.detailed(f"Quoted {fn=}, {args=}, {kwargs=} to {repr(_quote)}")
    return _quote


def quote(obj, *args, tag="$", **kwargs):
    log = Logger()
    if not callable(obj):
        assert len(args) == 0, f"Nonempty args for a noncallable obj: {args}"
        assert len(kwargs) == 0, f"Nonempty kwargs for a noncallable obj: {kwargs}"
        if hasattr(obj, 'quote') and callable(obj.quote):
            # Anything that knows how to quote itself renders itself.
            _quote = obj.quote()
        elif isinstance(obj, str):
            _quote = repr(obj)
        else:
            _quote = obj
        log.detailed(f"===============> Quoted {obj=} to {repr(_quote)}")
    else:
        func = obj
        fn = f"{func.__module__}.{func.__qualname__}"
        _quote = quotefn(fn, *args, tag=tag, **kwargs)
    return _quote

def dbx_repos(repopath=None):
    if repopath is None:
        repopath = DBX_GIT_REPO
    if repopath is None:
        return None, None
    paths = repopath.split(':')
    if len(paths) == 1:
        return None, paths[0]
    elif len(paths) == 2:
        if '/dbx' in paths[0]:
            return paths[0], paths[1]
        else:
            return paths[1], paths[0]
    else:
        raise ValueError(f"Too many paths in repopath: {repopath}")

def dbx_revisions(revision):
    if isinstance(revision, str):
        if ':' in revision:
            parts = revision.split(':')
            if len(parts) == 2:
                return parts[0], parts[1]
            else:
                raise ValueError(f"Revisions string must have exactly one ':': {revision}")
        return None, revision
    elif isinstance(revision, tuple):
        if len(revision) == 2:
            return revision
        else:
            raise ValueError(f"Revisions tuple must have exactly two elements: {revision}")
    elif revision is None:
        return None, None
    else:
        raise ValueError(f"Unknown revision type: {type(revision)}")

def dbx_versions(version):
    if isinstance(version, str):
        if ':' in version:
            parts = version.split(':')
            if len(parts) == 2:
                return parts[0], parts[1]
            else:
                raise ValueError(f"Version string must have at most one ':': {version}")
        return None, version
    return None, None


def gitwrkreposetup(revision=None, *, gitrepo=None, reason: str = "", log=None):
    if log is None:
        log = Logger(name="gitwrkreposetup")
    global DBX_GIT_REPO
    global DBX_USE_WORK_REPO
    global DBX_WORK_ROOT
    
    # A pinned interpreter came up with both repos already at `revision`, before
    # its first `import dbx`. There is nothing left to check out, and -- for dbx
    # -- nothing that COULD be: asking for a different revision here would rewind
    # the project underneath a dbx that cannot follow it, which is precisely the
    # split that produces a confidently wrong hash.
    pinned = os.environ.get('DBX_PINNED_REVISION')
    if pinned and revision is not None:
        if revision == pinned:
            log.verbose(f"already pinned to {pinned}; nothing to check out {reason}")
        else:
            log.warning(
                f"IGNORING requested revision {revision} {reason}: this interpreter is "
                f"pinned to {pinned} and dbx cannot be re-pinned in-process. Start a new "
                f"process (or Remote) pinned to {revision} instead."
            )
        return

    dbx_repo, project_repo = dbx_repos(gitrepo)
    dbx_rev, project_rev = dbx_revisions(revision)

    def setup_wrkrepo(repo, rev, name):
        nonlocal log
        if repo is None:
            return None
        log.verbose(f"SETTING UP WORK REPO for {name} from {repo=} {reason} with revision {rev}")
        wrkroot = tempfile.TemporaryDirectory()
        package = os.path.basename(repo)
        wrkrepo = os.path.join(wrkroot.name, package)
        _pkgpath = gitclone(repo, wrkrepo)
        assert wrkrepo == _pkgpath
        if rev is not None:
            gitcheckout(wrkrepo, rev)
            log.verbose(f"Checked out {wrkrepo} to revision {rev}")
        else:
            log.verbose(f"Using {wrkrepo} at HEAD")
        sys.path.insert(0, wrkrepo)
        return wrkroot, wrkrepo

    use_wrkrepo = os.environ.get('DBX_USE_WORK_REPO') == 'True' or revision is not None
    if use_wrkrepo and DBX_USE_WORK_REPO is None:
        if DBX_GIT_REPO is None:
            raise ValueError("DBX_GIT_REPO is not set and could not be detected. Cannot setup temporary wrkrepo.")

        # --- Early dirty check on the ORIGINAL repos ----------------------
        # Must happen *before* cloning: the clone uses HEAD, so any
        # uncommitted changes would be silently lost. setup_wrkrepo() below
        # runs unconditionally once we get past this check, so a dirty repo
        # is always a hard error — regardless of whether a specific revision
        # was requested — unless the caller explicitly opts in via
        # DBX_DIRTY_REPO_OK.
        def _check_dirty(path):
            if path is None:
                return
            repo = git.Repo(path)
            if repo.is_dirty() and not os.environ.get('DBX_DIRTY_REPO_OK'):
                msg = (
                    f"Dirty git repo: {path}: commit your changes before "
                    f"creating a work-repo clone (uncommitted changes would be lost)"
                )
                raise ValueError(msg)
        _check_dirty(dbx_repo)
        _check_dirty(project_repo)
        # ------------------------------------------------------------------

        dbx_wrk = setup_wrkrepo(dbx_repo, dbx_rev, "dbx")
        project_wrk = setup_wrkrepo(project_repo, project_rev, "project")

        DBX_WORK_ROOT = (dbx_wrk[0] if dbx_wrk else None, project_wrk[0] if project_wrk else None)
        
        dbx_wrkrepo = dbx_wrk[1] if dbx_wrk else None
        project_wrkrepo = project_wrk[1] if project_wrk else None
        
        if dbx_wrkrepo:
            wrkrepo_str = f"{dbx_wrkrepo}:{project_wrkrepo}"
        else:
            wrkrepo_str = project_wrkrepo
        
        globals()['DBX_USE_WORK_REPO'] = wrkrepo_str
        os.environ['DBX_GIT_REPO'] = wrkrepo_str
        # Signal to worker processes (Ray, multiprocessing) that we are
        # operating from a wrkrepo and the dirty check should be skipped.
        os.environ['DBX_WORK_ROOT'] = wrkrepo_str
        
        if 'DBX_USE_WORK_REPO' in os.environ:
            del os.environ['DBX_USE_WORK_REPO']
            
        log.verbose(f"DBX_USE_WORK_REPO: {wrkrepo_str}")

    elif revision is not None and DBX_USE_WORK_REPO is not None:
        # Work repos already exist (cloned at HEAD during import).
        # Checkout the requested revision so that subsequent imports
        # (e.g. project modules named by an evaluated expression)
        # pick up code from the correct commit.
        #
        # NOTE: modules already in sys.modules (including dbx itself)
        # will NOT be refreshed — only not-yet-imported modules benefit.
        dbx_wrkrepo, project_wrkrepo = dbx_repos(DBX_USE_WORK_REPO)
        if dbx_rev is not None and dbx_wrkrepo is not None:
            gitcheckout(dbx_wrkrepo, dbx_rev)
            log.verbose(f"Checked out existing work repo {dbx_wrkrepo} to revision {dbx_rev}")
        if project_rev is not None and project_wrkrepo is not None:
            gitcheckout(project_wrkrepo, project_rev)
            log.verbose(f"Checked out existing work repo {project_wrkrepo} to revision {project_rev}")
        # Clear finder caches so the import machinery sees the new files.
        importlib.invalidate_caches()

def gitrevision(*, log=Logger()):
    repopath = DBX_USE_WORK_REPO if DBX_USE_WORK_REPO is not None else DBX_GIT_REPO
    if repopath is not None:
        d_repo, project_repo = dbx_repos(repopath)
        
        def get_rev(path):
            if path is None:
                return None
            try:
                repo = git.Repo(path)
                # Dirty check is now performed in gitwrkreposetup() before
                # cloning, so we don't need to repeat it here.
                return repo.head.commit.hexsha
            except Exception as e:
                # git ≥ 2.35.2 raises ValueError / GitCommandError when the
                # work-repo temp dir is owned by a different process (common
                # in DDP subprocesses spawned by Lightning's
                # SubprocessScriptLauncher).  Fall back gracefully: the
                # revision is for audit purposes only.
                log.warning(
                    f"gitrevision: could not read HEAD from {path!r}: {e}"
                )
                return None

        dbx_rev = get_rev(d_repo)
        project_rev = get_rev(project_repo)
        
        if dbx_rev:
            revision = f"{dbx_rev}:{project_rev}"
        else:
            revision = project_rev
            
        log.detailed(f"Obtained git revision for git repo(s) {repopath}: {revision}")
    else:
        revision = None
    return revision


def gitclone(repopath, newpath):
    git.Repo.clone_from(repopath, newpath)
    return newpath


def gitcheckout(repopath, revision):
    repo = git.Repo(repopath)
    repo.git.checkout(revision)
    return repopath


#: Pin roots held for the lifetime of the process. A :class:`TemporaryDirectory`
#: deletes its tree when it is garbage collected, which would pull the clones out
#: from under a worker that is still importing from them.

def pintrampoline(printer=None, log=None):
    """Re-exec this process with dbx pinned, when the command line asks for it.

    Returns normally when there is nothing to do; otherwise DOES NOT RETURN.

    A CLI cannot pin dbx from the inside, for the same reason nothing else can:
    by the time ``dbx.pprint`` is running, ``import dbx`` has already happened and
    no checkout can dislodge it. So the process restarts itself --

      phase 1  (this call)  learn the revision, build the clones, exec
      phase 2  (the new image)  comes up with the pins already on sys.path

    -- with ``DBX_PINNED_REVISION`` as the guard that stops phase 2 trampolining
    again, and :func:`os.execve` rather than a subprocess so that stdout, exit
    status and signals stay exactly as they were.

    The revision cannot be inferred: the CLI argument is an arbitrary expression,
    and knowing which entry it refers to would mean evaluating it -- which is the
    thing that has to happen *after* the pin. So it must be stated::

        dbx.pprint --revision=<dbxsha>:<projsha>            "<expr>"
        dbx.pprint --pin-from="<expr yielding a revision>"  "<expr>"

    The second form evaluates only the selector, which must be read-only: phase 1
    and phase 2 both run it, so anything with side effects happens twice.

    *printer* names how phase 2 should render the result -- ``'pprint'`` for the
    printing entry points, ``None`` to evaluate and print nothing. It is baked
    into the generated runner rather than re-execing the console script, so the
    pin changes the ANSWER without also changing the presentation: pinning to a
    revision whose ``pprint`` predates a formatting fix should not resurrect the
    old formatting.
    """
    if log is None:
        log = Logger(name="pintrampoline")
    if os.environ.get('DBX_PINNED_REVISION'):
        return                                  # phase 2: already where we need to be

    revision = selector = pin_root = None
    rest = []
    for arg in sys.argv[1:]:
        if arg.startswith('--revision='):
            revision = arg.split('=', 1)[1]
        elif arg.startswith('--pin-from='):
            selector = arg.split('=', 1)[1]
        elif arg.startswith('--pin-root='):
            pin_root = arg.split('=', 1)[1]
        else:
            rest.append(arg)
    if revision is None and selector is None:
        return                                  # unpinned: today's behaviour, untouched

    if revision is None:
        lb = selector.find('(')
        lb = lb if lb != -1 else len(selector)
        _, cxt = get_named_const_and_cxt(selector[:lb])
        cxt['dbx'] = sys.modules['dbx']
        entry = __eval__(selector, globals(), cxt)
        revision = getattr(entry, 'revision', None)
        if revision is None:
            raise ValueError(f"--pin-from={selector!r} produced {type(entry).__name__}, which has no .revision")
        log.verbose(f"PIN: --pin-from resolved to revision {revision}")

    dbx_pin, project_pin = gitpinrepos(revision, pin_root=pin_root, log=log)
    pins = [p for p in (dbx_pin, project_pin) if p]

    env = dict(os.environ)
    env['PYTHONPATH'] = os.pathsep.join(pins + ([env['PYTHONPATH']] if env.get('PYTHONPATH') else []))
    env['DBX_GIT_REPO'] = ':'.join(pins)
    env['DBX_PINNED_REVISION'] = revision
    # The work repo exists to check out revisions in a running interpreter. The
    # pins already did that, before startup, and for dbx they did the part a work
    # repo never could.
    env.pop('DBX_USE_WORK_REPO', None)

    if printer not in _PINNED_RENDER:
        raise ValueError(f"printer must be one of {sorted(k for k in _PINNED_RENDER if k)} or None, got {printer!r}")
    # Beside the clones: that directory becomes sys.path[0] for phase 2, and it
    # holds only `<repo>-<sha>` entries, so it cannot shadow the pinned packages.
    runner = os.path.join(os.path.dirname(pins[0]), 'dbx_pinned_runner.py')
    with open(runner, 'w') as f:
        f.write(_PINNED_RUNNER.format(render=_PINNED_RENDER[printer]))

    argv = [sys.executable, runner, *rest]
    log.verbose(f"PIN: re-exec pinned to {revision}: PYTHONPATH={env['PYTHONPATH']}")
    sys.stdout.flush()
    sys.stderr.flush()
    os.execve(sys.executable, argv, env)


def pinshimdir(log=None):
    """Materialise :mod:`dbx._pinshim` as an importable ``dbxpinshim`` module dir.

    Returned path is meant for Ray's ``runtime_env['working_dir']``, which Ray
    uploads -- so unlike :func:`gitpinrepos` output it needs no shared
    filesystem. A few KB.
    """
    if log is None:
        log = Logger(name="pinshimdir")
    holder = tempfile.TemporaryDirectory(prefix='dbx-pinshim-')
    _DBX_PIN_ROOTS.append(holder)
    src = os.path.join(os.path.dirname(os.path.abspath(__file__)), '_pinshim.py')
    dst = os.path.join(holder.name, 'dbxpinshim.py')
    shutil.copyfile(src, dst)
    log.verbose(f"SHIM staged {src} -> {dst}")
    return holder.name


def pinhook_available(ray=None):
    """Whether this Ray supports ``runtime_env['worker_process_setup_hook']``.

    The hook is the only pre-import foothold in a worker, so without it the
    self-clone strategy is simply unavailable and pinning falls back to shipping
    clone paths (which needs a shared filesystem).
    """
    if ray is None:
        import ray
    known = getattr(getattr(ray, 'runtime_env', None), 'RuntimeEnv', None)
    return 'worker_process_setup_hook' in getattr(known, 'known_fields', ())


def gitpinrepos(revision, *, gitrepo=None, pin_root=None, log=None):
    """Clone the repos at *revision* and return ``(dbx_path, project_path)``.

    The companion of :func:`gitwrkreposetup` for the one thing that function
    cannot do: pin ``dbx`` itself. It deliberately does NOT touch ``sys.path``,
    because in this interpreter ``dbx`` is already imported and no path change
    can dislodge it. The clones are meant to be handed to a *fresh* interpreter
    via ``PYTHONPATH`` -- see :func:`remote`.

    Each returned path is the clone's root, i.e. the directory *containing* the
    ``dbx`` / project package, so it can go on ``PYTHONPATH`` as-is.

    Parameters
    ----------
    revision:
        ``'dbx_rev:project_rev'``. Either side may be ``None``, meaning
        "clone at HEAD".
    gitrepo:
        Source repos, in :func:`dbx_repos` form. Defaults to
        :data:`DBX_GIT_REPO`.
    pin_root:
        Where to put the clones. Must be visible to whoever will import from
        them: the default is a process-lifetime temporary directory, which is
        enough for workers on the same node, but a multi-node cluster needs a
        path on shared storage regardless of where Ray itself runs.
    """
    if log is None:
        log = Logger(name="gitpinrepos")
    dbx_repo, project_repo = dbx_repos(gitrepo)
    dbx_rev, project_rev = dbx_revisions(revision)

    if pin_root is None:
        root = tempfile.TemporaryDirectory()
        _DBX_PIN_ROOTS.append(root)
        pin_root = root.name
    else:
        os.makedirs(pin_root, exist_ok=True)

    def pin(repo, rev, name):
        if repo is None:
            return None
        if rev is None:
            # Cloning takes HEAD, so uncommitted work is silently absent from the
            # pin. Not an error -- an unpinned side is by definition "whatever is
            # current" -- but worth saying out loud, since the whole point of a
            # pin is that you know what you got.
            if git.Repo(repo).is_dirty():
                log.warning(f"PINNING {name} at HEAD from a dirty repo {repo}: uncommitted changes will not be in the pin")
        path = os.path.join(pin_root, f"{os.path.basename(repo)}-{rev or 'HEAD'}")
        if not os.path.isdir(path):
            # Clone to a scratch name and rename, so an interrupted clone cannot
            # leave a half-populated directory that the next call would reuse.
            staging = f"{path}.staging-{os.getpid()}"
            gitclone(repo, staging)
            if rev is not None:
                gitcheckout(staging, rev)
            os.rename(staging, path)
        log.verbose(f"PINNED {name} from {repo} at revision {rev or 'HEAD'} -> {path}")
        return path

    return pin(dbx_repo, dbx_rev, "dbx"), pin(project_repo, project_rev, "project")

class SlurmRayCluster:
    """
    Manages a Ray cluster running inside a Slurm job.
    """
    def __init__(self, gpus=0, mem='8G', cpus=1, partition=None, nodes=1, nodelist=None, time='01:00:00', log=Logger()):
        self.log = log
        self.job_id = None
        self.ray_address = None
        self.ray_client_address = None
        
        # Create a temp dir for slurm logs
        dbx_slurm_home = os.path.expanduser('~/.dbx/slurm')
        os.makedirs(dbx_slurm_home, exist_ok=True)
        self.tmpdir = tempfile.mkdtemp(prefix='job_', dir=dbx_slurm_home)
        
        partition_str = f"#SBATCH --partition={partition}" if partition else ""
        nodelist_str = f"#SBATCH --nodelist={nodelist}" if nodelist else ""
        if gpus is None:
            gpu_str = "##SBATCH --gres=gpu:0"
        elif isinstance(gpus, int):
            gpu_str = f"#SBATCH --gres=gpu:{gpus}" if gpus > 0 else f"##SBATCH --gres=gpu:0"
        else:
            gpu_str = f"#SBATCH --gres=gpu:{gpus}"
        
        script = f"""#!/bin/bash
#SBATCH --nodes={nodes}
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --time={time}
{partition_str}
{nodelist_str}
{gpu_str}
#SBATCH --job-name=dbx-ray
#SBATCH --output={self.tmpdir}/slurm-%j.out

nodes=$(scontrol show hostnames "$SLURM_JOB_NODELIST")
nodes_array=($nodes)
head_node=${{nodes_array[0]}}
# Try to get the IP address of the head node
head_node_ip=$(srun --nodes=1 --ntasks=1 -w "$head_node" hostname --ip-address | awk '{{print $1}}')
port=6379

echo "HEAD_NODE_IP: ${{head_node_ip}}"

# Start Ray head
echo "Starting Ray head on ${{head_node}} (${{head_node_ip}})"
srun --nodes=1 --ntasks=1 -w "$head_node" ray start --head --port=${{port}} --num-cpus={cpus} --num-gpus={gpus} --block &

# Start Ray workers
for ((i = 1; i < nodes; i++)); do
    node_i=${{nodes_array[$i]}}
    echo "Starting Ray worker on ${{node_i}}"
    srun --nodes=1 --ntasks=1 -w "$node_i" ray start --address="${{head_node_ip}}:${{port}}" --num-cpus={cpus} --num-gpus={gpus} --block &
done

wait
"""
        script_file = os.path.join(self.tmpdir, 'slurm_script.sh')
        with open(script_file, 'w') as f:
            f.write(script)
            
        cmd = ["sbatch", script_file]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"Failed to submit Slurm job: {res.stderr}")
            
        # Example output: "Submitted batch job 123456"
        self.job_id = res.stdout.strip().split()[-1]
        self.log.info(f"Submitted Slurm job {self.job_id} for Ray cluster")
        
        # Register for automatic cleanup on exit
        atexit.register(self.cancel)

        self.log.info("Waiting for Ray cluster to start (this may take a minute)...")
        start_time = time_module.time()
        try:
            while time_module.time() - start_time < 600: # 10 minutes max
                # Check if job is still in queue or running
                job_status_res = subprocess.run(["squeue", "-j", self.job_id, "-h", "-o", "%t"], capture_output=True, text=True)
                job_status = job_status_res.stdout.strip()
                
                if job_status == 'R':
                    # Job is running, try to get the head node (BatchHost)
                    batch_host_res = subprocess.run(["scontrol", "show", "job", self.job_id], capture_output=True, text=True)
                    match = re.search(r'BatchHost=(\S+)', batch_host_res.stdout)
                    if match:
                        head_node = match.group(1)
                        # Use the hostname directly (port is fixed at 6379 as per script)
                        addr = f"{head_node}:6379"
                        client_addr = f"ray://{head_node}:10001"
                        
                        # Check if port is open
                        try:
                            with socket.create_connection((head_node, 6379), timeout=1):
                                self.ray_address = addr
                                self.ray_client_address = client_addr
                                self.log.info(f"Ray cluster started at {head_node}:6379 (Client: {head_node}:10001)")
                                break
                        except (socket.timeout, ConnectionRefusedError):
                            pass

                if job_status_res.returncode == 0 and job_status:
                    if job_status in ['F', 'NF', 'TO', 'CA', 'CD']:
                        raise RuntimeError(f"Slurm job {self.job_id} failed or was cancelled (status: {job_status})")
                elif job_status_res.returncode != 0 and job_status_res.stderr:
                    # squeue might fail if job is already finished and moved to history
                    pass
                
                time_module.sleep(2)
        except KeyboardInterrupt:
            self.log.info(f"Interrupted while waiting for Ray cluster. Cancelling Slurm job {self.job_id}")
            self.cancel()
            raise

        if not self.ray_address:
            # Cleanup on timeout
            self.cancel()
            raise RuntimeError("Timed out waiting for Ray cluster to start on Slurm")
            
        # (Already logged cluster start in the loop)

    def cancel(self):
        """Cancel the Slurm job and cleanup temporary files."""
        if self.job_id:
            self.log.info(f"Cancelling Slurm job {self.job_id}")
            subprocess.run(["scancel", self.job_id])
            self.job_id = None
        
        if hasattr(self, 'tmpdir') and os.path.exists(self.tmpdir):
            try:
                shutil.rmtree(self.tmpdir)
            except Exception as e:
                self.log.debug(f"Failed to cleanup temp dir {self.tmpdir}: {e}")

class Remote:
    """
    A client-side proxy to a remote object running in a Ray Actor.
    """
    class RemoteObject:
        """
        Base class for remote proxies. Defined as a non-actor to support inheritance.
        """
        def __init__(self, obj):
            self._obj = obj

        def _wrap(self, val):
            """
            If val is a primitive (int, float, str, bool, None), return it directly.
            Otherwise, wrap it in a RemoteObject actor and return its handle.
            """
            if val is None or isinstance(val, (int, float, str, bool, list, dict, tuple)):
                return val
            
            # Module objects are often not stable when wrapped in new actors via Ray.
            # We return them directly (by value/pickle) to avoid crashing the worker process.

            if isinstance(val, types.ModuleType):
                return val
            
            # Universal proxying for all non-primitives.
            # Expanded call site with nested class as requested.
            # If actor creation fails (e.g. due to pickling issues), we fall back to returning by value.
            try:
                import ray
                return ray.remote(Remote.RemoteObject).remote(val)
            except Exception:
                return val

        def getattr(self, name):
            val = getattr(self._obj, name)
            return self._wrap(val)

        def call(self, name, *args, **kwargs):
            if hasattr(self, name) and name != 'obj' and not name.startswith('__'):
                attr = getattr(self, name)
            else:
                attr = getattr(self._obj, name)

            if not callable(attr):
                raise AttributeError(f"'{name}' is not callable")
            res = attr(*args, **kwargs)
            return self._wrap(res)

        def info(self, name):
            if hasattr(self, name):
                attr = getattr(self, name)
            else:
                attr = getattr(self._obj, name)
            is_call = callable(attr)
            return is_call, (None if is_call else self._wrap(attr))

        def environ(self, name):
            """Helper for verification of remote environment."""

            return os.environ.get(name)

    class RemoteDBX(RemoteObject):
        """
        Ray Actor that acts as a remote handle to the `dbx` module.
        Inherits directly from RemoteObject.
        """
        def __init__(self, revision=None):
            """
            Initialize the remote dbx instance.

            *revision* can only rewind the PROJECT repo. By the time this runs,
            resolving this very class has already imported dbx, and no checkout
            can dislodge an imported module -- so a dbx revision passed here is
            silently ignored. :func:`remote` pins dbx via ``PYTHONPATH`` instead
            and passes ``revision=None`` here once it has.
            """

            # Import dbx after setting environment variables.
            # We import the package to get the full namespace.
            import dbx

            # Call this here, because os.environ got updated and/or a new revision may need to be checked out
            dbx.gitwrkreposetup(revision=revision, reason="because of RemoteDBX initialization")
                
            super().__init__(dbx)

        def apply(self, func, *args, **kwargs):
            res = func(*args, **kwargs)
            return self._wrap(res)

        def apply_batch(self, funcs_args_kwargs):
            """
            Execute a sequence of (func, args, kwargs) on the remote actor.
            """
            results = []
            for func, args, kwargs in funcs_args_kwargs:
                res = func(*args, **kwargs)
                results.append(self._wrap(res))
            return results

    def __init__(self, handle=None, *, revision=None, slurm=None):
        """
        Initialize the remote proxy.
        """
        if handle is not None and revision is not None:
            raise ValueError("Remote: Cannot provide both 'handle' and 'revision'")
        self._handle = handle
        self._slurm = slurm
        if handle is None:
            import ray
            self._handle = ray.remote(Remote.RemoteDBX).remote(revision=revision)

    def __del__(self):
        """
        Ensure Slurm job is cancelled when the Remote instance is deleted.
        """
        # Safely check for _slurm without triggering __getattr__
        slurm = self.__dict__.get('_slurm')
        if slurm:
            slurm.cancel()
            self._slurm = None

    def __getattr__(self, name):
        """
        Dispatch attribute access to the remote actor.
        """
        if name.startswith('_') and not name.startswith('__'):
            raise AttributeError(name)

        import ray
        is_callable, value = ray.get(self._handle.info.remote(name))
        
        if is_callable:
            def wrapper(*args, **kwargs):
                import ray
                res = ray.get(self._handle.call.remote(name, *args, **kwargs))
                return self._unwrap_or_proxy(res)
            return wrapper
        else:
            return self._unwrap_or_proxy(value)

    def __getstate__(self):
        """
        Return the state of the remote object.
        """
        import ray
        return ray.get(self._handle.call.remote('__getstate__'))

    def _unwrap_or_proxy(self, val):
        import ray
        if isinstance(val, ray.actor.ActorHandle):
            return Remote(val) # Recursive wrapping
        return val

    def run(self, func, *args, **kwargs):
        """
        Execute a callable on the remote actor.
        """
        import ray
        res = ray.get(self._handle.apply.remote(func, *args, **kwargs))
        return self._unwrap_or_proxy(res)

    def run_batch(self, funcs_args_kwargs):
        """
        Execute a sequence of (func, args, kwargs) on the remote actor in one round-trip.
        """
        import ray
        results = ray.get(self._handle.apply_batch.remote(funcs_args_kwargs))
        return [self._unwrap_or_proxy(res) for res in results]


def remote(*, revision=None, slurm=None, conda=None, address=None, shared_repo=None,
           pin_root=None, pin_mode='auto', pin_source=None, gitrepo=None,
           working_dir='auto', log: Logger = Logger()):
    """
    Instantiate a remote dbx interpreter and return a Remote handle to it.

    When *revision* is given, BOTH repos are pinned in the worker before it
    imports anything. That is what lets a remote handle reproduce values whose
    identity depends on the code that produced them, which an in-process
    instantiation cannot -- ``dbx`` is already imported here and cannot be
    rewound. See the ``PYTHONPATH`` note below.

    Parameters
    ----------
    address:
        Ray cluster to connect to, for a cluster that was not started by
        *slurm*. ``None`` runs against a local Ray.
    shared_repo:
        Whether the workers can see :data:`_DBX_GIT_REPO_`, the original repo
        path. ``None`` (default) guesses: true whenever the workers might be on
        another host, i.e. when *slurm* or *address* is given. See the note on
        filesystem visibility below.
    pin_root:
        Forwarded to :func:`gitpinrepos` in ``pin_mode='pin_root'``. Same
        visibility requirement as *shared_repo*: the default temporary directory
        works only for workers on this host, so an off-host cluster needs a path
        on shared storage -- or ``pin_mode='shim'``, which removes the
        requirement instead of relocating it.
    pin_mode:
        How the worker comes up pinned. ``'pin_root'`` clones here and hands the
        worker paths; ``'shim'`` ships :mod:`dbx._pinshim` and lets each worker
        clone for itself. ``'auto'`` (default) picks ``'shim'`` when *pin_source*
        is given, or when the workers may be off-host and Ray supports the setup
        hook; otherwise ``'pin_root'``, which is cheaper on one host.
    pin_source:
        SPACE-separated clone sources for ``'shim'``, dbx first, matching the
        colon-separated parts of *revision*. Defaults to the repo paths in
        ``DBX_GIT_REPO``. Give git URLs here and no shared filesystem is needed
        at all. Implies ``pin_mode='shim'``.
    gitrepo:
        Override the repo paths the workers are told about, and that pinning
        clones from. Mirrors the *gitrepo* argument of the local instantiation
        path.
    working_dir:
        Ray ``runtime_env`` working directory. ``'auto'`` (the default) means:
        when pinning, hand Ray an EMPTY directory, because Ray otherwise puts
        this process's cwd at the head of the worker's ``sys.path`` -- and a
        driver run from inside the dbx or project checkout would then shadow the
        pins with the live tree. Pass a path to supply your own, or ``None`` to
        leave Ray's default alone and accept that cwd.

    Notes
    -----
    What decides both *shared_repo* and *pin_root* is whether the workers share
    a filesystem with this process -- NOT whether Ray itself is local. A Ray
    cluster reached over the network may well be running on this same host, and
    a local-looking one may not be.
    """
    import ray
    dbx_env = {k: v for k, v in os.environ.items() if k.startswith('DBX')}

    if DBX_USE_WORK_REPO is not None:
        dbx_env['DBX_GIT_REPO'] = DBX_USE_WORK_REPO

    # The work repo is a temporary directory, hence node-local by construction: a
    # worker on another host cannot see it. The original repo path (usually under
    # /home) is the only one with any chance of being shared, so that is what an
    # off-host cluster gets. This used to key off `slurm` alone, which left a
    # cluster reached via a plain `address` handing workers an unreadable /tmp path.
    offhost = bool(slurm) or address is not None
    if shared_repo is None:
        shared_repo = offhost
    if shared_repo:
        if _DBX_GIT_REPO_ is None:
            raise ValueError(
                "shared_repo requires an original repo path, but DBX_GIT_REPO was "
                "neither set nor detectable when dbx was imported"
            )
        dbx_env['DBX_GIT_REPO'] = _DBX_GIT_REPO_
    elif offhost and DBX_USE_WORK_REPO is not None:
        log.warning(
            f"shared_repo=False for an off-host cluster: workers are being given "
            f"{DBX_USE_WORK_REPO}, which is node-local and may not exist for them"
        )

    if gitrepo is not None:
        dbx_env['DBX_GIT_REPO'] = gitrepo

    runtime_env = {'env_vars': dbx_env}
    if conda:
        runtime_env['conda'] = conda

    # Pinning dbx CANNOT be delegated to dbx code running in the worker. Ray
    # resolves the Remote.RemoteDBX actor class by reference, so the worker
    # imports dbx.datablocks just to find the class -- dbx is in its sys.modules
    # before RemoteDBX.__init__ runs a line, and gitwrkreposetup never refreshes
    # an already-imported module (it says so itself). The pin has to be in place
    # before the worker's first `import dbx`, which leaves exactly two footholds:
    #
    #   'pin_root'  clone here, hand the worker paths on PYTHONPATH. Cheap and
    #               shared, but the clones must be READABLE by every worker.
    #   'shim'      ship a dbx-free bootstrap and run it from Ray's
    #               worker_process_setup_hook, which fires before any actor class
    #               is resolved; the worker clones for itself. Costs a clone per
    #               node, but the source can be a git URL, so no shared
    #               filesystem is needed anywhere.
    #
    # PYTHONPATH beats an editable install because setuptools *appends* its
    # _EditableFinder to sys.meta_path, leaving PathFinder -- and hence sys.path
    # -- ahead of it. The shim wins by inserting at sys.path[0] directly.
    worker_revision = revision
    use_shim = False
    if revision is not None:
        if pin_mode == 'auto':
            use_shim = pin_source is not None or (offhost and pinhook_available(ray))
        elif pin_mode == 'shim':
            if not pinhook_available(ray):
                raise ValueError(
                    "pin_mode='shim' needs a Ray with runtime_env['worker_process_setup_hook']; "
                    f"this one ({getattr(ray, '__version__', '?')}) has no such field"
                )
            use_shim = True
        elif pin_mode in ('pin_root', 'clone'):
            use_shim = False
        else:
            raise ValueError(f"pin_mode must be 'auto', 'shim' or 'pin_root', got {pin_mode!r}")

        # Tells the worker's gitwrkreposetup that it is already where it needs to
        # be, and lets it refuse a conflicting revision instead of half-applying one.
        dbx_env['DBX_PINNED_REVISION'] = revision

        if use_shim:
            if pin_source is None:
                dbx_repo, project_repo = dbx_repos(dbx_env.get('DBX_GIT_REPO'))
                dbx_rev, project_rev = dbx_revisions(revision)
                pairs = [(r, v) for r, v in ((dbx_repo, dbx_rev), (project_repo, project_rev)) if r and v]
                if not pairs:
                    raise ValueError(f"pin_mode='shim': no repo/revision pairs to pin from {revision!r}")
                pin_source = ' '.join(r for r, _ in pairs)
                pin_revision = ':'.join(v for _, v in pairs)
            else:
                pin_revision = revision
                if len(pin_source.split()) != len(pin_revision.split(':')):
                    raise ValueError(
                        f"pin_source has {len(pin_source.split())} entries but revision has "
                        f"{len(pin_revision.split(':'))}; they are zipped together, dbx first"
                    )
            dbx_env['DBX_PIN_SOURCE'] = pin_source
            dbx_env['DBX_PIN_REVISION'] = pin_revision
            runtime_env['worker_process_setup_hook'] = 'dbxpinshim.setup'
            log.verbose(f"PINNING by worker self-clone: {pin_source!r} at {pin_revision}")
        else:
            if offhost and pin_root is None:
                log.warning(
                    "PINNING into a temporary pin_root for an off-host cluster: workers "
                    "on other hosts will not see it -- pass pin_root on shared storage, "
                    "or pin_mode='shim' to have each worker clone for itself"
                )
            dbx_pin, project_pin = gitpinrepos(revision, gitrepo=dbx_env.get('DBX_GIT_REPO'),
                                               pin_root=pin_root, log=log)
            pins = [p for p in (dbx_pin, project_pin) if p]
            dbx_env['PYTHONPATH'] = os.pathsep.join(pins + [p for p in (os.environ.get('PYTHONPATH'),) if p])
            dbx_env['DBX_GIT_REPO'] = ':'.join(pins)
            log.verbose(f"PINNED worker to {revision} via PYTHONPATH={dbx_env['PYTHONPATH']}")

        # Both repos are already at the requested revision by the time the worker
        # runs, so it has nothing left to check out. Passing the revision on would
        # clone again to no effect -- and for dbx, to no *possible* effect.
        worker_revision = None

    # Ray prepends the driver's cwd to the worker's sys.path, AHEAD of anything
    # PYTHONPATH contributes. Run the driver from inside the dbx or project
    # checkout -- the most natural place to run it from -- and the live tree
    # silently wins over the pins. Handing Ray a working_dir displaces that entry.
    # The shim needs one anyway, to ship itself.
    if working_dir == 'auto':
        if use_shim:
            runtime_env['working_dir'] = pinshimdir(log=log)
        elif revision is not None:
            empty = tempfile.TemporaryDirectory(prefix='dbx-pin-workdir-')
            _DBX_PIN_ROOTS.append(empty)
            runtime_env['working_dir'] = empty.name
    elif use_shim:
        raise ValueError(
            "the self-clone shim needs working_dir to ship dbxpinshim.py, so it cannot "
            "be combined with an explicit working_dir; use pin_mode='pin_root', or "
            "leave working_dir='auto'"
        )
    elif working_dir is not None:
        runtime_env['working_dir'] = working_dir

    if slurm and slurm.ray_address:
        if ray.is_initialized():
            log.info("Re-initializing Ray to connect to Slurm Ray cluster...")
            ray.shutdown()
        # Use ray:// protocol for remote clusters to avoid shared /tmp/ray filesystem requirements
        cluster_address = getattr(slurm, 'ray_client_address', slurm.ray_address)
        ray.init(address=cluster_address, runtime_env=runtime_env, ignore_reinit_error=True)
    elif address is not None:
        if ray.is_initialized():
            log.info(f"Re-initializing Ray to connect to cluster at {address}...")
            ray.shutdown()
        ray.init(address=address, runtime_env=runtime_env, ignore_reinit_error=True)
    elif not ray.is_initialized():
        ray.init(runtime_env=runtime_env, ignore_reinit_error=True)
    
    log.verbose(f"INSTANTIATING Remote with env: {dbx_env}, revision: {revision}, slurm: {bool(slurm)}, conda: {conda}")
    return Remote(revision=worker_revision, slurm=slurm)

