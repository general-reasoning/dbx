def fs_full_path(fs, path):


    """Return *path* with the protocol prefix restored for remote filesystems.

    For local (``file``) filesystems the bare path is returned unchanged
    so that it remains compatible with Python's built-in ``open()``.
    For remote filesystems (``abfs``, ``gcs``, ``memory``, …) the protocol
    is re-attached via ``fs.unstrip_protocol()``.

    Special case: ``adlfs`` (Azure) — ``unstrip_protocol()`` drops the
    ``@account.dfs.core.windows.net`` portion.  We reconstruct the full
    ``abfss://container@account.dfs.core.windows.net/path`` form so that
    downstream consumers (e.g. MosaicML) can extract the account name.
    """
    protocol = fs.protocol if isinstance(fs.protocol, str) else fs.protocol[0]
    if protocol in ('file', 'local', ''):
        return path
    # adlfs: unstrip_protocol() loses the account — reconstruct manually.
    if protocol in ('abfs', 'az') and hasattr(fs, 'account_name') and fs.account_name:
        # path = "container/sub/path" → split into container + rest
        parts = path.split('/', 1)
        container = parts[0]
        rest = parts[1] if len(parts) > 1 else ''
        host = f"{fs.account_name}.dfs.core.windows.net"
        return f"abfss://{container}@{host}/{rest}"
    return fs.unstrip_protocol(path)


def parse_storage_options(raw: str | None) -> dict:
    """Parse a ``key=val;key=val;...`` string into a dict.

    Used to decode the ``DBX_STORAGE_OPTIONS`` environment variable.
    Returns an empty dict when *raw* is ``None`` or empty.

    Examples
    --------
    >>> parse_storage_options("account_name=myacct;account_key=secret")
    {'account_name': 'myacct', 'account_key': 'secret'}
    >>> parse_storage_options(None)
    {}
    """
    if not raw:
        return {}
    opts = {}
    for pair in raw.split(';'):
        pair = pair.strip()
        if not pair:
            continue
        if '=' not in pair:
            raise ValueError(
                f"Invalid DBX_STORAGE_OPTIONS fragment {pair!r}: expected key=value"
            )
        k, v = pair.split('=', 1)
        opts[k.strip()] = v.strip()
    return opts


def default_storage_options() -> dict:
    """Return storage options from ``DBX_STORAGE_OPTIONS`` env var, or ``{}``."""
    return parse_storage_options(os.environ.get('DBX_STORAGE_OPTIONS'))


def UNSAFE_allowed(what: str, *, OVERRIDE: bool = False):
    """Prompt the user for confirmation before an unsafe operation.

    Returns ``True`` if the user confirms or *OVERRIDE* is ``True``.
    """
    if not OVERRIDE:
        response = input(f"ARE YOU SURE YOU WANT TO EXECUTE UNSAFE CODE: {what}? [y/N]")
        if response.lower() != 'y':
            return False
    return True


def get_named_const_and_cxt(name):
    bits = name.split(".")
    modbits = bits[:-1]
    cxt = {}
    if not modbits:
        return None, cxt
    prefix = None
    last_mod = None
    for modbit in modbits:
        if prefix is not None:
            modname = prefix + "." + modbit
        else:
            modname = modbit
        try:
            mod = sys.modules.get(modname)
            if mod is None and "." in modname:
                mod = sys.modules.get(modname.split(".")[-1])
            if mod is None:
                mod = importlib.import_module(modname)
            prefix = modname
            cxt[modname] = mod
            last_mod = mod
        except (ModuleNotFoundError, AttributeError):
            break
    if last_mod is not None:
        obj = last_mod
        consumed_index = len(prefix.split("."))
        for bit in bits[consumed_index:]:
            obj = getattr(obj, bit)
        return obj, cxt
    constname = bits[-1]
    const = getattr(last_mod, constname) if last_mod is not None else None
    return const, cxt


def eval(name):
    """Evaluate a dbx term expression.

    Strings prefixed with ``@``, ``$``, or ``#`` are resolved as
    Python expressions in a context that includes imported modules.
    Iterables are evaluated element-wise.  Plain strings and other
    objects are returned as-is.
    However, 
        - We do not recursively eval Datablock ctor args/kwargs -- their string values
            are speclines that Datablocks store and evaluate lazily, 
            which preserves the Datablock's signature even after a trip through .quote().
        - Evaluating them here would expand e.g.
            "$os.path.join(...)" -> "/mnt/path/to/..." and bake
            the absolute path into self.spec, making subsignature() emit
            the concrete path rather than the portable specline, breaking
            signature() alignment.
    """
    def split_top_level_items(inner: str, sep: str = ','):
        out, buf, depth, quote, esc = [], [], 0, None, False
        for c in inner:
            if esc:
                buf.append(c); esc = False; continue
            if c == '\\':
                buf.append(c); esc = True; continue
            if quote is not None:
                buf.append(c)
                if c == quote:
                    quote = None
                continue
            if c in ('"', "'"):
                quote = c; buf.append(c); continue
            if c in ('(', '[', '{'):
                depth += 1
            elif c in (')', ']', '}'):
                depth -= 1
            elif c == sep and depth == 0:
                out.append(''.join(buf)); buf = []
                continue
            buf.append(c)
        if buf:
            out.append(''.join(buf))
        return out

    def get_named_args_kwargs(argkwargstr, cxt=None, *, func_is_datablock_ctor: bool = False):
        args = []
        kwargs = {}
        if cxt is None:
            cxt = {}
        cxt['dbx'] = sys.modules['dbx']
        if argkwargstr is not None:
            bits = split_top_level_items(argkwargstr)
            for bit in bits:
                bit = bit.strip()
                if not bit:
                    continue
                kwparts = split_top_level_items(bit, sep='=')
                
                if len(kwparts) == 2 and kwparts[0].strip().isidentifier():
                    k, v = kwparts[0].strip(), kwparts[1].strip()
                    if func_is_datablock_ctor:
                        val = v
                    else:
                        try:
                            val = ast.literal_eval(v)
                        except (NameError, SyntaxError, ValueError):
                            val = v
                        if isinstance(val, str):
                            if val.startswith("$") or val.startswith("@") or val.startswith("#"):
                                val = eval(val)
                            elif val.startswith("dbx."):
                                val = __eval__(val, cxt)
                        elif isinstance(val, (dict, list, tuple)):
                            if func_is_datablock_ctor and k == 'spec':
                                if not isinstance(val, dict):
                                    raise TypeError(f"spec must be a dict, got {type(val).__name__}")
                                _val = {}
                                """
                                    In a spec, evaluate only the Datablock args, the rest should remain unevaluated/unexpanded.
                                """
                                for _k, _v in val.items():
                                    _value = eval(_v)
                                    if isinstance(_value, Datablock):
                                        _val[_k] = _value
                                    else:
                                        _val[_k] = _v
                                val = _val
                            else:
                                val = eval(val)
                    kwargs[k] = val
                else:
                    if func_is_datablock_ctor:
                        arg = bit
                    else:
                        try:
                            arg = ast.literal_eval(bit)
                        except (NameError, SyntaxError, ValueError):
                            arg = bit
                        if isinstance(arg, str):
                            if arg.startswith("$") or arg.startswith("@") or arg.startswith("#"):
                                arg = eval(arg)
                            elif arg.startswith("dbx."):
                                arg = __eval__(arg, cxt)
                        elif isinstance(arg, (dict, list, tuple)):
                            arg = eval(arg)
                    args.append(arg)
        return args, kwargs

    def get_funcstr_argkwargstr(name):
        # TODO: replace with a regex
        lb = name.find("(")
        rb = name.rfind(")")
        if lb == -1 or rb == -1:
            funcstr = None
            argkwargstr = None
        else:
            funcstr = name[:lb]
            argkwargstr = name[lb + 1 : rb]
        return funcstr, argkwargstr

    Logger("eval").detailed(f" ====================> Evaluating term {repr(name)}")
    if isinstance(name, dict):
        term = {k: eval(v) for k, v in name.items()}
    elif isinstance(name, Iterable) and not isinstance(name, str):
        term = type(name)(eval(item) for item in name)
    elif isinstance(name, str):
        name = name.strip()
        if name.startswith("@") or name.startswith("#") or name.startswith("$"):
            _name_ = name[1:]
            funcstr, argkwargstr = get_funcstr_argkwargstr(_name_)
            if funcstr is None:
                term, _ = get_named_const_and_cxt(_name_)
            else:
                func, cxt = get_named_const_and_cxt(funcstr)
                cxt['dbx'] = sys.modules['dbx']
                from .datablocks import Datablock
                func_is_datablock_ctor = isinstance(func, type) and issubclass(func, Datablock)
                if argkwargstr is not None:
                    args, kwargs = get_named_args_kwargs(argkwargstr, cxt=cxt, func_is_datablock_ctor=func_is_datablock_ctor)
                    term = func(*args, **kwargs)
                else:
                    term = __eval__(_name_, cxt)

        else:
            term = name
    else:
        term = name
    return term


def exec(s=None, **kwargs):
    """Parse and execute a dbx expression from *s* or ``sys.argv``.

    When *s* is ``None``, the expression and keyword arguments are
    read from the command line (``sys.argv[1:]``).
    """
    from .datablocks import record_exec_journal
    if s is None:
        # Command line only: may re-exec this process pinned to a revision and
        # never return.
        pintrampoline()
        argv = [a for a in sys.argv[1:] if not a.startswith(PIN_FLAGS)]
        if not argv:
            raise ValueError(f"Too few args: {sys.argv}")
        s = argv[0]
        for arg in argv[1:]:
            if "=" in arg:
                k, v = arg.split("=", 1)
                try:
                    kwargs[k] = __eval__(v)
                except (NameError, SyntaxError):
                    kwargs[k] = v
    
    lb = s.find("(")
    lb = lb if lb != -1 else len(s)
    _, cxt = get_named_const_and_cxt(s[:lb])
    cxt.update(kwargs)
    r = __eval__(s, globals(), cxt)
    record_exec_journal(s)
    return r


def pprint(argstr=None, **kwargs):
    """Execute a dbx expression and pretty-print the result.

    Strings are printed RAW rather than passed to ``pprint.pprint``. pprint
    re-wraps a long str into implicitly-concatenated literals at width=80,
    which destroys any newlines and indentation the string itself carried: a
    multi-line ``quote()``/``cite()`` specline came out looking unindented,
    with each run of indent spaces shown as its own quoted chunk. Those
    methods return text meant to be read and copied, so print it as text.
    """
    if argstr is None:
        # Command line only. Tells the trampoline that phase 2 should render its
        # result the way THIS function would, rather than however the pinned
        # revision's pprint happens to. May re-exec and never return.
        pintrampoline(printer='pprint')
    r = exec(argstr, **kwargs)
    if isinstance(r, str):
        print(r)
    else:
        _pprint_.pprint(r)


def write_str(text, path, *, storage_options=None, log=Logger(), debug: bool = False):
    fs, _ = fsspec.url_to_fs(path, **(storage_options or {}))
    with fs.open(path, "w") as f:
        f.write(text)
        log.detailed(f"WROTE {path}")


def read_str(path, *, storage_options=None, log=Logger(), debug: bool = False):
    fs, _ = fsspec.url_to_fs(path, **(storage_options or {}))
    with fs.open(path, "r") as f:
        text = f.read()
        log.detailed(f"READ {path}")
    return text


